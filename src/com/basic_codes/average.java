package com.basic_codes;

public class average
 {
    public static void main(String[] args) {
        double num1 = 10;
        double num2 = 20;
        double num3 = 30;
        double num4 = 40;
        double num5 = 50;

        double sum = num1 + num2 + num3 + num4 + num5;
        double average = sum / 5;

        System.out.println("The average is: " + average);
    }
}

